
# Hello. In this code, I will be using f-strings to simply variables and print them out.

# I will be using my previous variable code to demonstrate how f-strings can be used to simplify the process of printing out variables.

# Instead of the traditional way of doing variables demonstrated below, I will be using f-strings to simplify the process.

age = 25
name = "John Smith"

print("This is the traditional way of printing out variables.")
print("My name is", name, "and I am", age, "years old.") 

# This is the traditional way of printing out variables. Below is my f-string version of the same code.

print("This version uses f-strings to simplify the process of printing out variables.")
print(f"My name is {name} and I am {age} years old.")

# Perfect. I will now use my previous variable code to show how f-strings can be used to simplfy variables.

