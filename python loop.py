# Welcome to the Python loop tutorial. In this tutorial, we will learn how to use while loops in Python.

number = 1

while number <= 5:
    print(number)
    number += 1

# This will continue to print the numbers 1 through 5, incrementing by 1 each time until it reaches 5.

# Now let's make a countdown timer from 5 to 1 using a while loop.

countdown = 5

while countdown > 0:
    print(countdown)
    countdown -= 1

# This will print the numbers 5 through 1, decrementing by 1 each time until it reaches 0.

# Now let's create a loop that prints the even numbers from 2 to 10.

even_number = 2

while even_number <= 10:
    print(even_number)
    even_number += 2

# This will print the even numbers 2, 4, 6, 8, and 10, incrementing by 2 each time until it reaches 10.

# Now let's do a loop that prints the odd numbers from 1 to 9.

odd_number = 1

while odd_number <= 9:
    print(odd_number)
    odd_number += 2

# This will print the odd numbers 1, 3, 5, 7, and 9, incrementing by 2 each time until it reaches 9.
